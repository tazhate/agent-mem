// Package event defines the runtime-neutral hook event that every adapter produces.
package event

import (
	"crypto/rand"
	"encoding/hex"
	"encoding/json"
	"time"
)

type Kind string

const (
	SessionStart  Kind = "session_start"
	Prompt        Kind = "prompt"
	ToolPre       Kind = "tool_pre"
	ToolPost      Kind = "tool_post"
	ToolFail      Kind = "tool_fail"
	TurnEnd       Kind = "turn_end"
	Compact       Kind = "compact"
	SubagentStart Kind = "subagent_start"
	SubagentStop  Kind = "subagent_stop"
	SessionEnd    Kind = "session_end"

	// Reindex is an internal signal to workers: memories changed project or visibility in bulk.
	Reindex Kind = "reindex"
)

// WantsContext reports whether the runtime can receive injected context for this kind,
// so the hook has to wait for recall instead of fire-and-forget.
func (k Kind) WantsContext() bool {
	switch k {
	case SessionStart, Prompt, ToolPre, ToolPost, ToolFail, SubagentStart, Compact:
		return true
	}
	return false
}

type Tool struct {
	Name     string          `json:"name"`
	UseID    string          `json:"use_id,omitempty"`
	Input    json.RawMessage `json:"input,omitempty"`
	Output   string          `json:"output,omitempty"`
	Error    string          `json:"error,omitempty"`
	ExitCode *int            `json:"exit_code,omitempty"`
}

// Failed reports whether the tool call ended with an error or non-zero exit code.
func (t *Tool) Failed() bool {
	return t != nil && (t.Error != "" || (t.ExitCode != nil && *t.ExitCode != 0))
}

type Event struct {
	// ID is generated by the hook so a retried delivery (socket, then spool) stores once.
	ID             string `json:"id,omitempty"`
	Runtime        string `json:"runtime"`
	NativeSession  string `json:"native_session"`
	Cwd            string `json:"cwd,omitempty"`
	Kind           Kind   `json:"kind"`
	Source         string `json:"source,omitempty"` // startup | resume | clear | compact
	TurnID         string `json:"turn_id,omitempty"`
	Prompt         string `json:"prompt,omitempty"`
	Tool           *Tool  `json:"tool,omitempty"`
	AgentID        string `json:"agent_id,omitempty"`
	AgentType      string `json:"agent_type,omitempty"`
	TranscriptPath string `json:"transcript_path,omitempty"`
	LastAssistant  string `json:"last_assistant,omitempty"`
	Model          string `json:"model,omitempty"`
	TS             int64  `json:"ts"` // unix ms
}

// SessionID is the amem identity of a session: stable, owned by us, independent of any LLM provider.
func (e *Event) SessionID() string { return e.Runtime + ":" + e.NativeSession }

func NowMS() int64 { return time.Now().UnixMilli() }

// NewID returns a random event id.
func NewID() string {
	b := make([]byte, 12)
	_, _ = rand.Read(b)
	return hex.EncodeToString(b)
}
